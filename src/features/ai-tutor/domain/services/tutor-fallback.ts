import { EN_LANGUAGE_VALUE, type LanguageValue } from "@/common/domain/value-objects/language";

export const MAX_FALLBACK_KEY_POINTS: number = 6;

const MIN_KEY_POINT_LENGTH: number = 25;

const MAX_KEY_POINT_LENGTH: number = 240;

interface FallbackTexts {
  readonly label: string;
  readonly pageIntro: (title: string) => string;
  readonly pageEmpty: string;
  readonly pageClosing: string;
  readonly contentQuestion: (title: string | undefined) => string;
  readonly freeChat: string;
}

const TEXTS: Readonly<Record<"es" | "en", FallbackTexts>> = {
  es: {
    label: "[Respuesta automática sin IA]",
    pageIntro: (title: string): string => `El asistente de IA no está disponible en este momento. Estos son los puntos clave de la página «${title}»:`,
    pageEmpty: "La página no tiene texto del que extraer puntos clave.",
    pageClosing: "Vuelve a pedir la profundización más tarde para obtener una explicación del asistente.",
    contentQuestion: (title: string | undefined): string =>
      `El asistente de IA no está disponible en este momento, así que no puedo responder tu pregunta. Mientras tanto, repasa el contenido de ${title ? `«${title}»` : "la lección"} (sus páginas, resúmenes y evaluaciones) y vuelve a preguntar más tarde.`,
    freeChat:
      "El asistente de IA no está disponible en este momento, así que no puedo responder tu pregunta. Puedes repasar los módulos y lecciones del curso de ventilación mecánica y volver a preguntar más tarde.",
  },
  en: {
    label: "[Automatic answer, not generated by AI]",
    pageIntro: (title: string): string => `The AI assistant is not available right now. These are the key points of the page "${title}":`,
    pageEmpty: "The page has no text to extract key points from.",
    pageClosing: "Ask for the deeper explanation again later to get an answer from the assistant.",
    contentQuestion: (title: string | undefined): string =>
      `The AI assistant is not available right now, so I cannot answer your question. Meanwhile, review the content of ${title ? `"${title}"` : "the lesson"} (its pages, summaries and evaluations) and ask again later.`,
    freeChat:
      "The AI assistant is not available right now, so I cannot answer your question. You can review the modules and lessons of the mechanical ventilation course and ask again later.",
  },
};

function textsFor(language: LanguageValue | undefined): FallbackTexts {
  return language === EN_LANGUAGE_VALUE ? TEXTS.en : TEXTS.es;
}

function firstSentence(line: string): string {
  const match: RegExpMatchArray | null = line.match(/^.+?[.!?](?=\s|$)/);
  const sentence: string = (match ? match[0] : line).trim();

  return sentence.length > MAX_KEY_POINT_LENGTH ? `${sentence.slice(0, MAX_KEY_POINT_LENGTH - 1).trimEnd()}…` : sentence;
}

// Headings and very short lines are skipped; each remaining paragraph contributes its first sentence, without repeats.
export function extractKeyPoints(text: string, max: number = MAX_FALLBACK_KEY_POINTS): string[] {
  const points: string[] = [];
  const seen: Set<string> = new Set<string>();

  for (const rawLine of text.split(/\n+/)) {
    const line: string = rawLine.replace(/^[\s\-*•\d.)]+/, "").trim();

    if (line.length < MIN_KEY_POINT_LENGTH) {
      continue;
    }

    const point: string = firstSentence(line);
    const key: string = point.toLowerCase();

    if (!seen.has(key)) {
      seen.add(key);
      points.push(point);
    }

    if (points.length >= max) {
      break;
    }
  }

  return points;
}

export function buildPageDeepenFallback(pageTitle: string, pageText: string, language?: LanguageValue): string {
  const texts: FallbackTexts = textsFor(language);
  const points: string[] = extractKeyPoints(pageText);
  const body: string = points.length > 0 ? points.map((point: string) => `- ${point}`).join("\n") : texts.pageEmpty;

  return [texts.label, texts.pageIntro(pageTitle), body, texts.pageClosing].join("\n\n");
}

export function buildContentQuestionFallback(contextTitle: string | undefined, language?: LanguageValue): string {
  const texts: FallbackTexts = textsFor(language);

  return `${texts.label}\n\n${texts.contentQuestion(contextTitle)}`;
}

export function buildFreeChatFallback(language?: LanguageValue): string {
  const texts: FallbackTexts = textsFor(language);

  return `${texts.label}\n\n${texts.freeChat}`;
}
