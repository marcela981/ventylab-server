/*
 * Funcionalidad: Pruebas del análisis determinista de notas
 * Descripción: Verifica el análisis por reglas sin IA: marca de análisis automático, conteo de notas y palabras, conceptos del glosario encontrados, cobertura de los términos del título (sin distinguir tildes) y sugerencias según la longitud y los conceptos, en español e inglés
 * Versión: 1.0
 * Autor: Marcela Mazo Castro
 * Proyecto: VentyLab
 * Tesis: Desarrollo de una aplicación web para la enseñanza de mecánica ventilatoria que integre un sistema de retroalimentación usando modelos de lenguaje
 * Institución: Universidad del Valle
 * Contacto: marcela.mazo@correounivalle.edu.co
 */
import { type NotesAnalysisContent } from "@/features/notes/domain/read-models/notes-analysis.read-model";
import { buildDeterministicNotesAnalysis } from "@/features/notes/domain/services/deterministic-notes-analysis";

describe("buildDeterministicNotesAnalysis", () => {
  it("counts notes and words, finds glossary concepts and the uncovered title terms", () => {
    const analysis: NotesAnalysisContent = buildDeterministicNotesAnalysis({
      texts: ["La PEEP mantiene los alvéolos abiertos.", "La presión meseta debe ser menor de 30 y la FiO2 se ajusta."],
      lessonTitle: "Oxigenación y presión",
      language: "es",
    });

    expect(analysis.summary).toMatch(/^Análisis automático sin IA/);
    expect(analysis.summary).toContain("2 nota(s), 19 palabras");
    expect(analysis.keyConcepts).toEqual(["PEEP", "FiO2", "Presión meseta / plateau pressure"]);
    expect(analysis.gaps).toEqual(["El término «oxigenación» del título no aparece en las notas"]);
    expect(analysis.suggestions[0]).toContain("Amplía tus notas");
    expect(analysis.suggestions[analysis.suggestions.length - 1]).toContain("Vuelve a pedir el análisis con IA");
  });

  it("suggests the key parameters when no glossary concept appears, in English", () => {
    const analysis: NotesAnalysisContent = buildDeterministicNotesAnalysis({ texts: ["Some general remarks."], language: "en" });

    expect(analysis.summary).toMatch(/^Automatic analysis, not generated by AI/);
    expect(analysis.keyConcepts).toEqual([]);
    expect(analysis.gaps).toEqual([]);
    expect(analysis.suggestions).toEqual(expect.arrayContaining([expect.stringContaining("Include the key ventilation parameters")]));
  });
});
